export function t(locale: CleanerLocale, key: string): string {
  return messages[locale]?.[key] ?? messages.fr[key] ?? key;
}

export function tr(locale: CleanerLocale, key: string, vars: Record<string, string | number | null | undefined>): string {
  return t(locale, key).replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? ""));
}
