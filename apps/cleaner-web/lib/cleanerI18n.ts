export type CleanerLocale = "fr" | "en" | "ru";

export function getCleanerLocale(raw: unknown): CleanerLocale {
  return raw === "en" || raw === "ru" || raw === "fr" ? raw : "fr";
}

export function intlLocale(locale: CleanerLocale): string {
  if (locale === "en") return "en-GB";
  if (locale === "ru") return "ru-RU";
  return "fr-FR";
}

